export const WAPDA_SCHEDULE_MAP = new Map<string, WapdaScheduleItem>(
  WAPDA_SCHEDULE_RAW.map(([sc, desc, um, aup]) => [
    sc,
    { sc, desc, um, aup }
  ])
);

/**
 * Normalizes code query to find schedule item matching either 5-digit or unpadded store code
 */
export function lookupWapdaScheduleItem(code: string): WapdaScheduleItem | undefined {
  if (!code) return undefined;
  const clean = code.trim();
  if (WAPDA_SCHEDULE_MAP.has(clean)) {
    return WAPDA_SCHEDULE_MAP.get(clean);
  }
  // Try 5-digit pad
  const padded = clean.padStart(5, '0');
  if (WAPDA_SCHEDULE_MAP.has(padded)) {
    return WAPDA_SCHEDULE_MAP.get(padded);
  }
  // Try removing leading zero
  const unpadded = clean.replace(/^0+/, '');
  for (const [key, item] of WAPDA_SCHEDULE_MAP.entries()) {
    if (key.replace(/^0+/, '') === unpadded) {
      return item;
    }
  }
  return undefined;
}
